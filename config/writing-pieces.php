// Helper function to get piece by slug
function getPieceBySlug($slug) {
    global $writingPieces;
    foreach ($writingPieces as $piece) {
        if ($piece['slug'] === $slug) {
            return $piece;
        }
    }
    return null;
}

// Helper function to get pieces by category
function getPiecesByCategory($category) {
    global $writingPieces;
    if ($category === 'all' || $category === '') {
        return $writingPieces;
    }
    return array_filter($writingPieces, function($piece) use ($category) {
        return $piece['category'] === $category;
    });
}

// Helper function to get related pieces (same category, excluding current)
function getRelatedPieces($currentSlug, $category, $limit = 4) {
    global $writingPieces;
    $related = [];
    foreach ($writingPieces as $piece) {
        if ($piece['slug'] !== $currentSlug && $piece['category'] === $category) {
            $related[] = $piece;
            if (count($related) >= $limit) break;
        }
    }
    return $related;
}
